class Gauss1lsProblem(BaseProblem):
    def __init__(self):
        n = 8
        x0 = np.array(
            [9.70e01, 9.00e-03, 1.00e02, 6.50e01, 2.00e01, 7.00e01, 1.78e02, 1.65e01]
        ).astype(np.float64)
        super().__init__("Gauss1ls", n, x0)

    def _f(self, x):
        b1, b2, b3, b4, b5, b6, b7, b8 = x
        y_fit = (
            b1 * np.exp(-b2 * xs)
            + b3 * np.exp(-((xs - b4) ** 2) / (b5**2))
            + b6 * np.exp(-((xs - b7) ** 2) / (b8**2))
            # + e # e means noise, which is not included in the model
        )
        return np.sum((y_fit - ys) ** 2)

    def _g(self, x):
        # Gradient of the Gauss1ls function
        b1, b2, b3, b4, b5, b6, b7, b8 = x
        grad = np.zeros_like(x)
        B1 = b1 * np.exp(-b2 * xs)
        B2 = b3 * np.exp(-((xs - b4) ** 2) / (b5**2))
        B3 = b6 * np.exp(-((xs - b7) ** 2) / (b8**2))
        y_fit = B1 + B2 + B3
        residuals = y_fit - ys
        grad[0] = 2 * np.sum(residuals * B1 / b1)
        grad[1] = 2 * np.sum(residuals * B1 * (-xs))
        grad[2] = 2 * np.sum(residuals * B2 / b3)
        grad[3] = 2 * np.sum(residuals * B2 * 2 * (xs - b4) / (b5**2))
        grad[4] = 2 * np.sum(residuals * B2 * 2 * ((xs - b4) ** 2) / (b5**3))
        grad[5] = 2 * np.sum(residuals * B3 / b6)
        grad[6] = 2 * np.sum(residuals * B3 * 2 * (xs - b7) / (b8**2))
        grad[7] = 2 * np.sum(residuals * B3 * 2 * ((xs - b7) ** 2) / (b8**3))
        return grad
